"""CLI for fully local autonomous analytics: python main.py --help"""
import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

from autonalytics.cleaning import create_approval
from autonalytics.runner import run_pipeline
from autonalytics.settings import ROOT, file_in_data, load_config
from autonalytics.storage import already_processed, interrupted_run, recent_runs
from autonalytics.utils import sha256_file


def build_parser():
    p=argparse.ArgumentParser(description='Autonomous Analytics — offline-first, human-governed data analysis')
    sub=p.add_subparsers(dest='cmd',required=True)
    run=sub.add_parser('run',help='Analyze one dataset')
    run.add_argument('--config',default=None); run.add_argument('--input',default=None)
    run.add_argument('--goal',default=None); run.add_argument('--mode',choices=['rules','auto','ollama'],default=None)
    run.add_argument('--max-steps',type=int,default=None)
    run.add_argument('--approval-file',default=None,help='Approvals generated by the approve command')
    run.add_argument('--resume',default=None,help='Continue a checkpointed run by run_id')
    approve=sub.add_parser('approve',help='Approve selected cleaning proposals for a run')
    approve.add_argument('--run-id',required=True)
    group=approve.add_mutually_exclusive_group(required=True)
    group.add_argument('--all',action='store_true')
    group.add_argument('--ids',nargs='+',help='One or more proposal IDs')
    history=sub.add_parser('history',help='List stored experiment runs')
    history.add_argument('--limit',type=int,default=15)
    watch=sub.add_parser('watch',help='Periodically analyze an input when its content changes')
    watch.add_argument('--config',default=None); watch.add_argument('--input',default=None)
    watch.add_argument('--mode',choices=['rules','auto','ollama'],default=None)
    watch.add_argument('--interval-minutes',type=float,default=30)
    watch.add_argument('--once',action='store_true')
    return p


def main(argv=None):
    args=build_parser().parse_args(argv)
    if args.cmd=='history':
        for r in recent_runs(args.limit):
            print(f"{r['run_id']} | {r['status']:<9} | steps={r['steps']:<3} | {r['source_file']} | {r['goal'][:65]}")
        return 0
    if args.cmd=='approve':
        path=ROOT/'outputs'/args.run_id/'cleaning_proposals.json'
        if not path.is_file(): raise FileNotFoundError(path)
        result=create_approval(path,ids=args.ids,all_items=args.all)
        print(f'Approval written: {result}')
        print('Next: python main.py run --approval-file "'+str(result)+'"')
        return 0
    if args.cmd=='run':
        cfg=load_config(args.config,{'input_file':args.input, 'goal':args.goal,
                                    'mode':args.mode, 'max_steps':args.max_steps})
        result=run_pipeline(cfg, approval_file=args.approval_file, resume=args.resume)
        return 0 if result['state']['status']=='complete' else 2
    if args.cmd=='watch':
        if args.interval_minutes < 0.1: raise ValueError('--interval-minutes >= 0.1')
        cfg=load_config(args.config,{'input_file':args.input,'mode':args.mode})
        print('Watching local input for changes. Ctrl+C to stop.')
        had_failure = False
        while True:
            try:
                path=file_in_data(cfg['input_file'])
                digest=sha256_file(path)
                if already_processed(digest,cfg['goal']):
                    print('Dataset already analyzed for this goal; no new run.', flush=True)
                else:
                    config_hash=hashlib.sha256(json.dumps(cfg,sort_keys=True,ensure_ascii=False).encode()).hexdigest()
                    incomplete=interrupted_run(digest,cfg['goal'],config_hash)
                    result=run_pipeline(cfg,resume=incomplete)
                    print(f"{'Resumed' if incomplete else 'New'} run: {result['run_id']}", flush=True)
            except Exception as exc:
                had_failure = True
                print('Watch iteration failed:',str(exc)[:180],file=sys.stderr)
            if args.once: break
            time.sleep(args.interval_minutes*60)
        return 1 if had_failure else 0
    return 1


if __name__=='__main__':
    try: sys.exit(main())
    except KeyboardInterrupt:
        print('Cancelled by user'); sys.exit(130)
    except Exception as exc:
        print(f'ERROR: {type(exc).__name__}: {exc}',file=sys.stderr); sys.exit(1)
